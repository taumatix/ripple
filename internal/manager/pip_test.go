func TestPipMatches(t *testing.T) {
	p := Pip{Dir: "/"}
	for f, want := range map[string]bool{"requirements.txt": true, "a/requirements-dev.txt": true, "requirements/base.txt": true,
		"pyproject.toml": true, "x/pyproject.toml": true, "constraints.txt": true, "requirements.in": true, "constraints-dev.in": true, "Pipfile": true, "other.in": false, "notes.txt": false, "requirements.lock": false,
		"venv/requirements.txt": false, "node_modules/a/pyproject.toml": false} {
		if got := p.Matches(f); got != want {
			t.Errorf("Matches(%q) = %v", f, got)
		}
	}
	if (Pip{Dir: "/app"}).Matches("other/requirements.txt") {
		t.Error("outside the directory")
	}
}

func TestPipRequirementsExtract(t *testing.T) {
	deps, err := Pip{Dir: "/"}.Extract("requirements.txt", []byte(pipRequirements))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, d := range deps {
		if d.Datasource != model.DatasourcePip || d.Manager != "pip" {
			t.Errorf("%+v", d)
		}
		got = append(got, d.Package+d.Version)
	}
	// numpy is a floor with an upper bound (tracked); pandas is a `==2.*` wildcard (tracked, moves past its prefix), django a prerelease: not tracked.
	want := "requests==2.31.0 flask-login~=0.6.2 click>=8.0 numpy>=1.20,<2 pandas==2.* legacy==1.0"
	if strings.Join(got, " ") != want {
		t.Errorf("got  %v\nwant %s", got, want)
	}
}

func TestPipRequirementsApplyKeepsEverythingElse(t *testing.T) {
	p := Pip{Dir: "/"}
	cases := []struct{ pkg, ver, to, from, into string }{
		{"requests", "==2.31.0", "2.32.3", "requests==2.31.0   # pinned", "requests==2.32.3   # pinned"},
		{"flask-login", "~=0.6.2", "0.6.3", `Flask_Login[async] ~= 0.6.2 ;`, `Flask_Login[async] ~= 0.6.3 ;`},
		{"click", ">=8.0", "8.1.7", "click>=8.0\n", "click>=8.1.7\n"},
		{"legacy", "==1.0", "1.1.post1", "legacy==1.0", "legacy==1.1.post1"},
	}
	for _, tc := range cases {
		out, err := p.Apply([]byte(pipRequirements), model.Dependency{File: "requirements.txt", Package: tc.pkg, Version: tc.ver}, "", tc.to)
		if err != nil {
			t.Fatalf("%s: %v", tc.pkg, err)
		}
		if want := strings.Replace(pipRequirements, tc.from, tc.into, 1); string(out) != want {
			t.Errorf("%s: only the version moves:\n%s", tc.pkg, out)
		}
	}
}

func TestPipGeneratedAndHashedFilesAreLocks(t *testing.T) {
	gen := "#\n# This file is autogenerated by pip-compile with Python 3.12\n#\nrequests==2.31.0\n"
	if deps, _ := (Pip{Dir: "/"}).Extract("requirements.txt", []byte(gen)); len(deps) != 0 {
		t.Errorf("a pip-compile output is a lock: %+v", deps)
	}
	uv := "# This file was autogenerated by uv via the following command:\nrequests==2.31.0\n"
	if deps, _ := (Pip{Dir: "/"}).Extract("requirements.txt", []byte(uv)); len(deps) != 0 {
		t.Errorf("a uv output is a lock: %+v", deps)
	}
}

