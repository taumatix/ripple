const pipRequirements = `# deps
requests==2.31.0   # pinned
Flask_Login[async] ~= 0.6.2 ; python_version >= "3.8"
click>=8.0
numpy>=1.20,<2
pandas==2.*
django==4.2rc1
sixlib===1.0
pkg @ https://example.com/pkg.whl
-e git+https://example.com/x.git#egg=x
-r other.txt
hashed==1.0.0 \
    --hash=sha256:abc
inline==3.0.0 --hash=sha256:def
legacy==1.0
tilde~=3
`

func TestPipMatches(t *testing.T) {
	p := Pip{Dir: "/"}
	for f, want := range map[string]bool{"requirements.txt": true, "a/requirements-dev.txt": true, "requirements/base.txt": true,
		"pyproject.toml": true, "x/pyproject.toml": true, "constraints.txt": false, "requirements.lock": false,
		"venv/requirements.txt": false, "node_modules/a/pyproject.toml": false} {
		if got := p.Matches(f); got != want {
			t.Errorf("Matches(%q) = %v", f, got)
		}
	}
	if (Pip{Dir: "/app"}).Matches("other/requirements.txt") {
		t.Error("outside the directory")
	}
}

func TestPipRequirementsExtract(t *testing.T) {
	deps, err := Pip{Dir: "/"}.Extract("requirements.txt", []byte(pipRequirements))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, d := range deps {
		if d.Datasource != model.DatasourcePip || d.Manager != "pip" {
			t.Errorf("%+v", d)
		}
		got = append(got, d.Package+d.Version)
	}
	// numpy has a second clause, pandas a wildcard, django a prerelease: not tracked.
	want := "requests==2.31.0 flask-login~=0.6.2 click>=8.0 legacy==1.0"
	if strings.Join(got, " ") != want {
		t.Errorf("got  %v\nwant %s", got, want)
	}
}

func TestPipRequirementsApplyKeepsEverythingElse(t *testing.T) {
	p := Pip{Dir: "/"}
	cases := []struct{ pkg, ver, to, from, into string }{
		{"requests", "==2.31.0", "2.32.3", "requests==2.31.0   # pinned", "requests==2.32.3   # pinned"},
		{"flask-login", "~=0.6.2", "0.6.3", `Flask_Login[async] ~= 0.6.2 ;`, `Flask_Login[async] ~= 0.6.3 ;`},
		{"click", ">=8.0", "8.1.7", "click>=8.0\n", "click>=8.1.7\n"},
		{"legacy", "==1.0", "1.1.post1", "legacy==1.0", "legacy==1.1.post1"},
	}
	for _, tc := range cases {
		out, err := p.Apply([]byte(pipRequirements), model.Dependency{File: "requirements.txt", Package: tc.pkg, Version: tc.ver}, "", tc.to)
		if err != nil {
			t.Fatalf("%s: %v", tc.pkg, err)
		}
		if want := strings.Replace(pipRequirements, tc.from, tc.into, 1); string(out) != want {
			t.Errorf("%s: only the version moves:\n%s", tc.pkg, out)
		}
	}
}

func TestPipGeneratedAndHashedFilesAreLocks(t *testing.T) {
	gen := "#\n# This file is autogenerated by pip-compile with Python 3.12\n#\nrequests==2.31.0\n"
	if deps, _ := (Pip{Dir: "/"}).Extract("requirements.txt", []byte(gen)); len(deps) != 0 {
		t.Errorf("a pip-compile output is a lock: %+v", deps)
	}
	uv := "# This file was autogenerated by uv via the following command:\nrequests==2.31.0\n"
	if deps, _ := (Pip{Dir: "/"}).Extract("requirements.txt", []byte(uv)); len(deps) != 0 {
		t.Errorf("a uv output is a lock: %+v", deps)
	}
}

const pyproject = `[build-system]
requires = ["setuptools>=61"]

[project]
name = "app"
dependencies = [
  "requests==2.31.0",   # http
  'Click~=8.1.0',
  "attrs>=23.1; python_version>'3.8'",
  "other @ https://example.com/o.whl",
  "ranged>=1,<2",
]

[project.optional-dependencies]
dev = ["pytest==7.4.0", "requests==2.31.0"]

[dependency-groups]
lint = ["ruff>=0.1.0", {include-group = "dev"}]

[tool.other]
dependencies = ["notme==1.0.0"]
`

func TestPipPyprojectExtractAndApply(t *testing.T) {
	p := Pip{Dir: "/"}
	deps, err := p.Extract("pyproject.toml", []byte(pyproject))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, d := range deps {
		got = append(got, d.Package+d.Version)
	}
	if want := "requests==2.31.0 click~=8.1.0 attrs>=23.1 pytest==7.4.0 ruff>=0.1.0"; strings.Join(got, " ") != want {
		t.Errorf("got  %v\nwant %s", got, want)
	}
	out, err := p.Apply([]byte(pyproject), model.Dependency{File: "pyproject.toml", Package: "requests", Version: "==2.31.0"}, "", "2.32.3")
	if err != nil {
		t.Fatal(err)
	}
	if want := strings.ReplaceAll(pyproject, "requests==2.31.0", "requests==2.32.3"); string(out) != want {
		t.Errorf("both places move, nothing else:\n%s", out)
	}
	out, _ = p.Apply([]byte(pyproject), model.Dependency{File: "pyproject.toml", Package: "click", Version: "~=8.1.0"}, "", "8.1.7")
	if want := strings.Replace(pyproject, "'Click~=8.1.0'", "'Click~=8.1.7'", 1); string(out) != want {
		t.Errorf("click:\n%s", out)
	}
}

func TestPipApplyStaleAndRefusals(t *testing.T) {
	p := Pip{Dir: "/"}
	d := model.Dependency{File: "requirements.txt", Package: "requests", Version: "==1.0.0"}
	if _, err := p.Apply([]byte(pipRequirements), d, "", "1.0.1"); !errors.Is(err, ErrStale) {
		t.Errorf("err = %v", err)
	}
	d.Version = "==2.31.0"
	if _, err := p.Apply([]byte(pipRequirements), d, "", "3.0rc1"); err == nil {
		t.Error("a prerelease is not a target")
	}
	if _, err := p.Apply([]byte(pipRequirements), d, "other", "2.32.0"); !errors.Is(err, ErrUnsupported) {
		t.Errorf("rename err = %v", err)
	}
}

func TestPipIndexOverride(t *testing.T) {
	for _, tc := range []struct {
		name, body string
		want       bool
	}{
		{"requirements.txt", "requests==1\n--extra-index-url https://pypi.corp/simple\n", true},
		{"requirements.txt", "-i https://pypi.corp/simple\n", true},
		{"requirements.txt", "--index-url=https://pypi.corp/simple\n", true},
		{"requirements.txt", "# --extra-index-url https://x\nrequests==1\n", false},
		{"pip.conf", "[global]\nextra-index-url = https://pypi.corp/simple\n", true},
		{"pip.conf", "[global]\ntimeout = 5\n", false},
		{"pyproject.toml", "[[tool.poetry.source]]\nname = \"corp\"\n", true},
		{"pyproject.toml", "[[tool.uv.index]]\nurl = \"https://x\"\n", true},
		{"pyproject.toml", "[tool.uv]\nextra-index-url = [\"https://x\"]\n", true},
		{"pyproject.toml", pyproject, false},
	} {
		if got := PipIndexOverride(tc.name, []byte(tc.body)); got != tc.want {
			t.Errorf("%s %q = %v", tc.name, tc.body, got)
		}
	}
}
