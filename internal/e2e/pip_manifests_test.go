package e2e

import (
	"context"
	"github.com/taumatix/ripple/internal/model"
	"strings"
	"testing"
	"time"

	"github.com/taumatix/ripple/internal/store"
	"github.com/taumatix/ripple/internal/testutil"
)

const poetryPyproject = `[tool.poetry]
name = "app"

[tool.poetry.dependencies]
python = "^3.9"
requests = "^2.31.0"
click = { version = "~8.0", extras = ["x"] }
exact = "1.0.0"
anything = "*"
gitdep = { git = "https://example.com/g.git", version = "^1.0" }

[tool.poetry.dependencies.detail]
version = "^1.0"
optional = true

[tool.poetry.group.dev.dependencies]
pytest = ">=7.0,<8"

[build-system]
requires = ["setuptools>=61"]
`

const pipfile = `[[source]]
url = "https://pypi.org/simple"
verify_ssl = true
name = "pypi"

[packages]
flask = "==2.0.0"
star = "*"

[dev-packages]
black = {version = ">=23.1", extras = ["d"]}
`

const reqIn = "numpy>=1.20,<2\n"
const reqGenerated = "#\n# This file is autogenerated by pip-compile with Python 3.12\n#\nnumpy==1.20.0\n"

func TestPipPoetryPipfileRangesAndInFiles(t *testing.T) {
	forEach(t, func(t *testing.T, st store.Store) {
		idx := testutil.NewPyPI(t)
		lim := defaultLimits()
		lim.OpenPRLimit = 20
		e := newEnvOpts(t, st, lim, opts{pypi: idx})
		for _, p := range [][2]string{{"requests", "2.31.0"}, {"click", "8.0.0"}, {"exact", "1.0.0"}, {"detail", "1.0.0"},
			{"pytest", "7.0.0"}, {"setuptools", "61.0"}, {"flask", "2.0.0"}, {"black", "23.1.0"}, {"numpy", "1.20.0"},
			{"anything", "1.0"}, {"gitdep", "1.0"}, {"star", "1.0"}} {
			idx.Publish(p[0], p[1])
		}
		e.gh.AddRepo("acme/app", map[string]string{".ripple.yaml": pipConfig, "pyproject.toml": poetryPyproject,
			"Pipfile": pipfile, "requirements.in": reqIn, "requirements.txt": reqGenerated})
		start(t, e, "acme/app")
		if n := len(e.deps("acme/app")); n != 9 {
			t.Fatalf("requests click exact detail pytest setuptools flask black numpy are tracked, got %d: %+v", n, e.deps("acme/app"))
		}
		e.clock.Advance(time.Minute)
		for _, p := range [][2]string{{"requests", "2.32.3"}, {"click", "8.1.7"}, {"exact", "1.0.1"}, {"detail", "1.1.0"},
			{"pytest", "7.4.4"}, {"pytest", "8.0.0"}, {"setuptools", "70.0"}, {"flask", "2.3.3"}, {"black", "24.2.0"},
			{"numpy", "1.26.4"}, {"numpy", "2.0.0"}, {"anything", "2.0"}, {"gitdep", "2.0"}, {"star", "2.0"}} {
			idx.Publish(p[0], p[1])
		}
		e.tick()
		e.tick()

		want := map[string]struct{ file, from, to string }{
			"requests":   {"pyproject.toml", `requests = "^2.31.0"`, `requests = "^2.32.3"`},
			"click":      {"pyproject.toml", `version = "~8.0"`, `version = "~8.1.7"`},
			"exact":      {"pyproject.toml", `exact = "1.0.0"`, `exact = "1.0.1"`},
			"detail":     {"pyproject.toml", "[tool.poetry.dependencies.detail]\nversion = \"^1.0\"", "[tool.poetry.dependencies.detail]\nversion = \"^1.1.0\""},
			"pytest":     {"pyproject.toml", `">=7.0,<8"`, `">=7.4.4,<8"`},
			"setuptools": {"pyproject.toml", `setuptools>=61"`, `setuptools>=70.0"`},
			"flask":      {"Pipfile", `"==2.0.0"`, `"==2.3.3"`},
			"black":      {"Pipfile", `">=23.1"`, `">=24.2.0"`},
			"numpy":      {"requirements.in", ">=1.20,<2", ">=1.26.4,<2"},
		}
		for _, v := range [][2]string{{"pytest", "7.4.4"}, {"numpy", "1.26.4"}} {
			j, ok, err := e.st.GetJob(context.Background(), model.JobKey("acme/app", model.DatasourcePip, v[0], v[1]))
			t.Logf("DEBUG %s: %+v %v %v %+v", v[0], j.Key, ok, err, e.deps("acme/app"))
		}
		prs := e.gh.PRs("acme/app")
		if len(prs) != len(want) {
			t.Fatalf("one PR per tracked project (%d), got %d: %+v", len(want), len(prs), prs)
		}
		for _, pr := range prs {
			var name string
			for n := range want {
				if strings.HasPrefix(pr.Head, "ripple/pip/"+n+"-") {
					name = n
				}
			}
			if name == "" {
				t.Fatalf("unexpected branch %q", pr.Head)
			}
			w := want[name]
			files := map[string]string{"pyproject.toml": poetryPyproject, "Pipfile": pipfile, "requirements.in": reqIn, "requirements.txt": reqGenerated}
			files[w.file] = strings.Replace(files[w.file], w.from, w.to, 1)
			for f, exp := range files {
				if got, _ := e.gh.FileAt("acme/app", pr.Head, f); got != exp {
					t.Errorf("%s: %s must change only %q:\n%s", pr.Head, f, w.to, got)
				}
			}
			if name == "numpy" && (!strings.Contains(pr.Body, "Lock files not regenerated") || !strings.Contains(pr.Body, "`requirements.txt`")) {
				t.Errorf("the pip-compile output beside requirements.in is stale, the body must say so:\n%s", pr.Body)
			}
		}
	})
}
