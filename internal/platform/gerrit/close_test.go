package gerrit_test

import (
	"strings"
	"testing"

	"github.com/taumatix/ripple/internal/model"
	"github.com/taumatix/ripple/internal/platform"
	"github.com/taumatix/ripple/internal/platform/gerrit"
)

const (
	closeProject = "acme/app"
	closeTopic   = "ripple/lib-v1"
	ripplesEmail = "ripple@users.noreply.invalid"
)

var _ platform.PRCloser = (*gerrit.Client)(nil)

// openRipplePR has ripple propose closeTopic, as the engine does, and returns the PR
// the engine would hold for it.
func openRipplePR(t *testing.T) (*fakeGerrit, *gerrit.Client, platform.PR) {
	t.Helper()
	f := newFakeGerrit(t)
	f.AddRepo(closeProject, map[string]string{"go.mod": "module x\n"})
	c := newClient(f)
	if ok, err := checkoutAndPush(t, c, closeProject, closeTopic, "go.mod", "module x\n\nrequire a v1\n"); err != nil || !ok {
		t.Fatalf("push: %v %v", ok, err)
	}
	ch := f.Changes(closeProject)[0]
	return f, c, platform.PR{Number: ch.Number, Head: ch.Topic}
}

func closeIt(c *gerrit.Client, pr platform.PR) (bool, error) {
	return c.CloseUntouchedPR(ctx, model.Repo{FullName: closeProject}, pr, "superseded by v2")
}

func status(f *fakeGerrit) string { return f.Changes(closeProject)[0].Status }

func abandonPosts(f *fakeGerrit) int {
	n := 0
	for _, r := range f.Requests() {
		if strings.HasSuffix(r.Path, "/abandon") {
			n++
		}
	}
	return n
}

// rest-api-changes.md "Abandon Change": the message becomes the review comment.
func TestCloseUntouchedAbandonsWithOneComment(t *testing.T) {
	f, c, pr := openRipplePR(t)
	ok, err := closeIt(c, pr)
	if err != nil || !ok {
		t.Fatalf("close: %v %v", ok, err)
	}
	ch := f.Changes(closeProject)[0]
	if ch.Status != "ABANDONED" || ch.AbandonMessage != "superseded by v2" {
		t.Errorf("change %+v", ch)
	}
}

// Several patch sets, all ripple's (it pushed the same branch again), are untouched.
func TestCloseUntouchedIgnoresRipplesOwnLaterPatchSets(t *testing.T) {
	f, c, pr := openRipplePR(t)
	if ok, err := checkoutAndPush(t, c, closeProject, closeTopic, "go.mod", "module x\n\nrequire a v2\n"); err != nil || !ok {
		t.Fatalf("second push: %v %v", ok, err)
	}
	if ok, err := closeIt(c, pr); err != nil || !ok {
		t.Fatalf("close: %v %v", ok, err)
	}
	if status(f) != "ABANDONED" {
		t.Errorf("status %s", status(f))
	}
}

